#!/usr/bin/env bash
# 配布物に含まれる依存ライブラリのライセンスを THIRD-PARTY-NOTICES.txt に書き出す。
# `pnpm notices` から呼ばれる。依存を足したり上げたりしたら流し直してコミットする
# (lib.rs のテストが、直接依存が Cargo.lock / pnpm-lock.yaml の version で載っているかを見る。
# CI は `--check` で、生成し直した結果がコミット済みのファイルと一致するかを見る)。
#
# 節は 3 つ:
# - JavaScript: `vite build` の client の bundle に実際に入ったモジュールから package を引く
#   (vite.config.js の listBundledModules)。package.json の dependencies とは一致しない
#   (plugin-opener は Rust 側からしか使わず、svelte / kit は devDependencies のまま bundle される)
#   ので、手で一覧を持たない。CSS は JS のモジュールに出ないので、preflight を出力する
#   tailwindcss だけ足す。
# - Rust: cargo-about。設定は src-tauri/about.toml。
# - Native: crate が C のソースや静的ライブラリを同梱してリンクするもの (vendored libgit2、
#   Windows でソースからビルドされる zlib、Windows の WebView2 Loader)。crate 自身のライセンスは
#   Rust の節に出るが、同梱物のライセンスは別物なのでここで足す。
#
# 本文を同梱していない package / 同梱物の本文は vendor-licenses/<name>@<version>/ に、その
# version の upstream から取ったものを置いて読む。version を上げると見つからずに失敗するので、
# その時は同じように取り直す。
set -euo pipefail

cd "$(dirname "$0")/.."

# version で出力の書式が変わり、手元で作り直したファイルが CI の --check で落ちるので固定する。
# CI はこの行を読んで同じ version を入れる
CARGO_ABOUT_VERSION=0.9.2

OUT="THIRD-PARTY-NOTICES.txt"
CHECK=false
case "${1:-}" in
  "") ;;
  --check) CHECK=true ;;
  *)
    echo "Usage: $0 [--check]" >&2
    exit 1
    ;;
esac

if [ "$(cargo about --version 2>/dev/null)" != "cargo-about $CARGO_ABOUT_VERSION" ]; then
  echo "Error: cargo-about $CARGO_ABOUT_VERSION is required. Run:" >&2
  echo "  cargo install cargo-about --version $CARGO_ABOUT_VERSION --locked --features cli" >&2
  exit 1
fi
if [ ! -d node_modules ]; then
  echo "Error: node_modules is missing. Run: pnpm install" >&2
  exit 1
fi

WORK=$(mktemp -d "${OUT}.work.XXXXXX")
# 同じディレクトリに作る。別ファイルシステムの /tmp からの mv はコピーになり、途中で
# 止まると壊れた出力が残る
TMP=$(mktemp "${OUT}.XXXXXX")
trap 'rm -rf "$WORK" "$TMP"' EXIT

DAGSCAPE_BUNDLED_MODULES_OUT="$WORK/modules.json" pnpm exec vite build --logLevel error
cargo about generate --manifest-path src-tauri/Cargo.toml -c src-tauri/about.toml --locked --fail \
  --format json -o "$WORK/about.json"
# 配布ターゲットごとに解決する。付けないと他 OS 専用の crate が混ざる
TRIPLES=(aarch64-apple-darwin x86_64-apple-darwin x86_64-pc-windows-msvc)
for triple in "${TRIPLES[@]}"; do
  cargo metadata --manifest-path src-tauri/Cargo.toml --locked --format-version 1 \
    --filter-platform "$triple" > "$WORK/metadata-$triple.json"
done

node - "$WORK" "${TRIPLES[@]}" > "$TMP" <<'NODE'
const fs = require("fs");
const path = require("path");

const [work, ...triples] = process.argv.slice(2);
const root = process.cwd();
const out = [];
const print = (line = "") => out.push(line);
const read = (file) => fs.readFileSync(file, "utf8");
const heading = (title) => {
  print("#".repeat(80));
  print(`# ${title}`);
  print("#".repeat(80));
  print();
};
const textOf = (file) => read(file).replace(/\r\n/g, "\n").replace(/\s+$/, "");
// LICENSE.spdx のような SPDX のメタデータは本文ではないので除く
const licenseFiles = (dir) =>
  fs
    .readdirSync(dir)
    .filter((f) => /^(LICEN[CS]E|COPYING)/i.test(f) && !/\.spdx$/i.test(f))
    .sort();
const noticeFiles = (dir) => fs.readdirSync(dir).filter((f) => /^NOTICE/i.test(f)).sort();
const vendored = (name, version) => {
  const dir = path.join(root, "vendor-licenses", `${name}@${version}`);
  return fs.existsSync(dir) ? dir : null;
};
const entry = (license, users, body) => {
  print("=".repeat(80));
  print(`License: ${license}`);
  print();
  print("Used by:");
  for (const user of users) print(`  ${user}`);
  print();
  for (const text of body) {
    print(text);
    print();
  }
};
// Apache-2.0 §4(d) は NOTICE の引き継ぎを求めるので、本文の後ろに付ける
const notices = (dir, label) =>
  noticeFiles(dir).map((f) => `NOTICE (${label}):\n\n${textOf(path.join(dir, f))}`);

print("THIRD-PARTY NOTICES");
print();
print("Dagscape bundles the open source libraries listed below. Each entry gives the");
print("license, the packages it applies to, and the license text as shipped by the");
print("package. Generated by scripts/generate-third-party-notices.sh; do not edit by hand.");
print();

// ---------------------------------------------------------------------------------------------
// JavaScript
// ---------------------------------------------------------------------------------------------
heading("JavaScript packages (bundled into the web view)");

// bundler が差し込むコード (仮想モジュール) と、それを出す package。ここに無い仮想モジュールが
// 出たら、出所を確かめて足す
const VIRTUAL_MODULES = {
  "\0rolldown/runtime.js": ["rolldown", "vite"],
  "\0vite/preload-helper.js": ["vite", null],
};
// CSS はモジュール一覧に出ない。app.css の @import "tailwindcss" が preflight を出力する
const CSS_PACKAGES = ["tailwindcss"];

const packageDir = (name, from) => {
  if (!from) return fs.realpathSync(path.join(root, "node_modules", name));
  // pnpm は推移依存を .pnpm/<pkg>@<ver>/node_modules/ に並べるので、依存元の隣から引く
  const fromDir = fs.realpathSync(path.join(root, "node_modules", from));
  let base = fromDir;
  for (let i = 0; i < from.split("/").length; i++) base = path.dirname(base);
  return path.join(base, name);
};

const packages = new Map();
const addPackage = (dir) => {
  const manifest = JSON.parse(read(path.join(dir, "package.json")));
  const key = `${manifest.name}@${manifest.version}`;
  if (!packages.has(key)) packages.set(key, { dir, manifest });
};
for (const id of JSON.parse(read(path.join(work, "modules.json")))) {
  const clean = id.split("?")[0];
  const match = clean.match(/^(.*\/node_modules\/(?:@[^/]+\/)?[^/]+)\//);
  if (match) {
    addPackage(match[1]);
  } else if (clean.startsWith("\0")) {
    const source = VIRTUAL_MODULES[clean];
    if (!source) throw new Error(`unknown virtual module in the bundle: ${JSON.stringify(id)}`);
    addPackage(packageDir(...source));
  } else if (!clean.startsWith(root + path.sep)) {
    throw new Error(`module outside the repository and node_modules: ${id}`);
  }
}
for (const name of CSS_PACKAGES) addPackage(packageDir(name, null));
if (packages.size < 3) throw new Error(`too few bundled packages: ${[...packages.keys()]}`);

for (const { dir, manifest } of [...packages.values()].sort((a, b) =>
  a.manifest.name.localeCompare(b.manifest.name),
)) {
  const { name, version } = manifest;
  const repo =
    typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url;
  if (!manifest.license) throw new Error(`${name} ${version} has no license in package.json`);
  let source = dir;
  let files = licenseFiles(dir);
  if (files.length === 0) {
    source = vendored(name, version);
    files = source ? licenseFiles(source) : [];
  }
  if (files.length === 0) {
    throw new Error(
      `${name} ${version} ships no license text; copy it from that version's upstream into ` +
        `vendor-licenses/${name}@${version}/`,
    );
  }
  const body = files.map((f) =>
    files.length > 1 ? `--- ${f} ---\n${textOf(path.join(source, f))}` : textOf(path.join(source, f)),
  );
  entry(manifest.license, [`${name} ${version}${repo ? ` (${repo})` : ""}`], [
    ...body,
    ...notices(dir, `${name} ${version}`),
  ]);
}

// ---------------------------------------------------------------------------------------------
// Rust
// ---------------------------------------------------------------------------------------------
heading("Rust crates (compiled into the binary)");

const metadata = triples.map((triple) => ({
  triple,
  ...JSON.parse(read(path.join(work, `metadata-${triple}.json`))),
}));
const packageById = new Map();
for (const m of metadata) for (const p of m.packages) packageById.set(p.id, p);
const ownCrates = new Set(
  metadata.flatMap((m) => m.workspace_members.map((id) => packageById.get(id).name)),
);
const crateDirs = new Map();
for (const p of packageById.values()) {
  crateDirs.set(`${p.name} ${p.version}`, path.dirname(p.manifest_path));
}

const about = JSON.parse(read(path.join(work, "about.json")));
const licenses = about.licenses
  .map((license) => ({
    ...license,
    users: license.used_by
      .map((u) => u.crate)
      .filter((crate) => !ownCrates.has(crate.name))
      .sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version)),
  }))
  .filter((license) => license.users.length > 0);
for (const license of licenses) {
  const crateNotices = license.users.flatMap((crate) => {
    const dir = crateDirs.get(`${crate.name} ${crate.version}`);
    if (!dir) throw new Error(`${crate.name} ${crate.version} is not in cargo metadata`);
    return notices(dir, `${crate.name} ${crate.version}`);
  });
  entry(
    license.name,
    license.users.map(
      (crate) => `${crate.name} ${crate.version}${crate.repository ? ` (${crate.repository})` : ""}`,
    ),
    [license.text.replace(/\r\n/g, "\n").replace(/\s+$/, ""), ...crateNotices],
  );
}

// ---------------------------------------------------------------------------------------------
// Native
// ---------------------------------------------------------------------------------------------
heading("Native libraries (C sources and static libraries shipped inside the crates above)");

// 配布物に入る (通常依存で辿れる) package だけを、ターゲットごとに集める
const shipped = new Map(); // id -> { pkg, features, triples }
for (const m of metadata) {
  const nodes = new Map(m.resolve.nodes.map((n) => [n.id, n]));
  const stack = [...m.workspace_members];
  const seen = new Set();
  while (stack.length) {
    const id = stack.pop();
    if (seen.has(id)) continue;
    seen.add(id);
    const node = nodes.get(id);
    const found = shipped.get(id) ?? { pkg: packageById.get(id), features: node.features, triples: [] };
    found.triples.push(m.triple);
    shipped.set(id, found);
    for (const dep of node.deps) {
      if (dep.dep_kinds.some((kind) => kind.kind === null)) stack.push(dep.pkg);
    }
  }
}

// name -> 同梱物。files は crate のディレクトリからの相対パス、vendor は vendor-licenses の
// 名前を crate の version から引く関数。null は同梱物が無いことを確かめた crate
const NATIVE = {
  "libgit2-sys": (found) =>
    found.features.includes("vendored")
      ? {
          library: "libgit2",
          // libgit2 は GPL-2.0 に linking exception が付いたもの。COPYING は libgit2 が
          // 同梱する依存 (pcre2 / llhttp / xdiff 等) のライセンスもまとめて含む
          license: "GPL-2.0-only with the libgit2 linking exception",
          files: ["libgit2/COPYING"],
        }
      : null,
  // Apple のターゲットでは OS の libz にリンクし、Windows ではこのソースから静的にビルドされる
  "libz-sys": (found) =>
    found.triples.some((t) => t.includes("windows"))
      ? { library: "zlib", license: "Zlib", files: ["src/zlib/LICENSE"], only: "Windows" }
      : null,
  // WebView2LoaderStatic.lib (Microsoft の WebView2 SDK) が静的にリンクされる。crate は本文を
  // 同梱していないので、SDK の NuGet package の LICENSE.txt / NOTICE.txt を vendor-licenses に置く
  "webview2-com-sys": (found) => {
    const sdk = { "0.39.1": "1.0.3800.47" }[found.pkg.version];
    if (!sdk) {
      throw new Error(
        `webview2-com-sys ${found.pkg.version}: add the WebView2 SDK version it bundles ` +
          "(crates/update-bindings/src/main.rs WEBVIEW2_VERSION at that release) and vendor its license",
      );
    }
    return {
      library: `Microsoft WebView2 Loader (WebView2 SDK ${sdk})`,
      license: "BSD-3-Clause",
      vendor: `Microsoft.Web.WebView2@${sdk}`,
      only: "Windows",
    };
  },
};
// links や -sys を持つが、第三者のネイティブコードを同梱しない crate (OS の API への binding、
// crate 自身の C、ビルド用のメタデータとしての links)
const NO_BUNDLED_NATIVE = new Set([
  "core-foundation-sys",
  "defmt",
  "dirs-sys",
  "fsevent-sys",
  "objc2-exception-helper",
  "tauri",
  "tauri-plugin-dialog",
  "tauri-plugin-fs",
  "tauri-plugin-opener",
  "tauri-plugin-store",
  "windows-sys",
]);

const natives = [...shipped.values()]
  .filter(({ pkg }) => pkg.links || pkg.name.endsWith("-sys"))
  .filter(({ pkg }) => !ownCrates.has(pkg.name))
  .sort((a, b) => a.pkg.name.localeCompare(b.pkg.name) || a.pkg.version.localeCompare(b.pkg.version));
let nativeCount = 0;
for (const found of natives) {
  const { name, version } = found.pkg;
  if (NO_BUNDLED_NATIVE.has(name)) continue;
  const describe = NATIVE[name];
  if (!describe) {
    throw new Error(
      `${name} ${version} may bundle native code; check what it links and add it to NATIVE ` +
        "or NO_BUNDLED_NATIVE in scripts/generate-third-party-notices.sh",
    );
  }
  const native = describe(found);
  if (!native) continue;
  const dir = path.dirname(found.pkg.manifest_path);
  let body;
  if (native.vendor) {
    const source = path.join(root, "vendor-licenses", native.vendor);
    if (!fs.existsSync(source)) throw new Error(`missing vendor-licenses/${native.vendor}/`);
    body = fs.readdirSync(source).sort().map((f) => `--- ${f} ---\n${textOf(path.join(source, f))}`);
  } else {
    body = native.files.map((f) => textOf(path.join(dir, f)));
  }
  const only = native.only ? `, ${native.only} build only` : "";
  entry(native.license, [`${native.library} (bundled by ${name} ${version}${only})`], body);
  nativeCount++;
}
if (nativeCount === 0) throw new Error("no native library found; libgit2 is expected");

process.stdout.write(out.join("\n").replace(/\n+$/, "\n"));
NODE

if $CHECK; then
  if ! diff -u "$OUT" "$TMP"; then
    echo "Error: $OUT is out of date. Run: pnpm notices" >&2
    exit 1
  fi
  echo "$OUT is up to date"
else
  mv "$TMP" "$OUT"
  echo "Wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
fi
